export async function build() {
  const out: Record<string, unknown> = {
    $comment: 'Generated by packages/js/scripts/generate-cross-language-fixtures.ts',
    secret: SECRET,
    timestamp: TIMESTAMP,
    cases: {},
  };
  for (const p of supportedProviders) {
    const signed = await signTestPayload(p, samples[p], SECRET, { timestamp: TIMESTAMP });
    (out.cases as Record<string, unknown>)[p] = signed;
  }
  (out.cases as Record<string, unknown>)['flutterwave-v3'] = await signTestPayload(
    'flutterwave',
    { event: 'charge.completed', data: { id: 1, tx_ref: 't', amount: 100, currency: 'NGN', status: 'successful' } },
    SECRET,
    { flutterwaveVersion: 'v3' },
  );
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const target = fileURLToPath(new URL('../../../fixtures/cross-language.json', import.meta.url));
  build().then((o) => writeFileSync(target, `${JSON.stringify(o, null, 2)}\n`));
}
